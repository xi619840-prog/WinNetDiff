"""Build the standard-library-only, deterministic single-file distribution.

Application imports are removed only from the generated artifact. Real source
modules use ordinary explicit imports; the CI compares this generated file.
"""
from __future__ import annotations
import argparse
import ast
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = [
    'core/models', 'core/messages', 'core/atomic', 'core/windows', 'core/keyfile', 'core/privacy', 'core/process', 'core/config', 'core/catalog',
    'gui/catalog', 'core/scenario_catalog', 'core/extension_catalog', 'core/i18n', 'probes/transport',
    'collectors/security', 'collectors/routes', 'collectors/proxy', 'analysis/ownership', 'probes/proxy_path', 'repairs/manager',
    'reports/export', 'reports/share_card', 'core/snapshots', 'analysis/evidence', 'collectors/dns_audit', 'analysis/dns_rules', 'probes/pmtu', 'analysis/scenarios', 'analysis/verification',
    'analysis/rules', 'core/engine', 'gui/app', 'cli',
]


def build_source() -> str:
    result = ['#!/usr/bin/env python3', '# -*- coding: utf-8 -*-',
              '# Generated by scripts/build_standalone.py; edit winnetdiff/ instead.',
              '# Copyright (c) 2026 Alden. MIT License; see LICENSE.',
              'from __future__ import annotations', '_STANDALONE_BUILD = True', '']
    sources = {}
    for module in MODULES:
        path = ROOT / 'winnetdiff' / (module + '.py')
        source = path.read_text(encoding='utf-8')
        sources['winnetdiff.' + module.replace('/', '.')] = (source, ast.parse(source, filename=str(path)))
    for module in MODULES:
        path = ROOT / 'winnetdiff' / (module + '.py')
        identity = 'winnetdiff.' + module.replace('/', '.')
        text, tree = sources[identity]
        excluded = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module == '__future__':
                excluded.update(range(node.lineno, node.end_lineno + 1))
            elif isinstance(node, ast.ImportFrom) and (node.level or node.module == 'winnetdiff' or str(node.module).startswith('winnetdiff.')):
                # Explicit contract: flatten only known, unaliased top-level
                # application imports. Reject scoped/conditional imports rather
                # than silently changing execution timing or local bindings.
                if node not in tree.body:
                    raise ValueError('Scoped application import is unsupported: ' + module + ':' + str(node.lineno))
                dependency = importlib.util.resolve_name('.' * node.level + (node.module or ''), identity.rsplit('.', 1)[0]) if node.level else node.module
                if dependency not in sources:
                    raise ValueError('Dependency absent from explicit module manifest: ' + str(dependency))
                exports = set()
                for item in sources[dependency][1].body:
                    if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                        exports.add(item.name)
                    elif isinstance(item, (ast.Import, ast.ImportFrom)):
                        exports.update(alias.asname or alias.name.split('.')[0] for alias in item.names)
                    elif isinstance(item, ast.Assign):
                        exports.update(target.id for target in item.targets if isinstance(target, ast.Name))
                    elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                        exports.add(item.target.id)
                if any(alias.name == '*' or alias.asname not in (None, alias.name) or alias.name not in exports for alias in node.names):
                    raise ValueError('Unsupported alias, wildcard or missing application symbol: ' + module)
                excluded.update(range(node.lineno, node.end_lineno + 1))
            elif isinstance(node, ast.Import) and any(alias.name.startswith('winnetdiff') for alias in node.names):
                raise ValueError('Module imports must use from-import for the standalone build: ' + module)
        result.extend(['', '# --- ' + module + '.py ---', ''])
        result.extend(line for index,line in enumerate(text.splitlines(), 1) if index not in excluded)
    result.extend(['', "if __name__ == '__main__':", '    raise SystemExit(main())', ''])
    source = '\n'.join(result)
    compile(source, 'windows_net_diffdiag.py', 'exec')
    return source


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=ROOT / 'windows_net_diffdiag.py')
    args = parser.parse_args()
    expected = build_source()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding='utf-8') != expected:
            print('Standalone artifact is stale. Run scripts/build_standalone.py.')
            return 1
    else:
        args.output.write_text(expected, encoding='utf-8', newline='\n')
        print(str(args.output))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
